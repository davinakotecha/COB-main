// Generates the CSS custom properties from @carbon/themes, @carbon/colors and @carbon/motion,
// so no hex value is typed in from memory. A token that does not exist is an error, not a gap.
import * as themes from '@carbon/themes';
import * as colors from '@carbon/colors';
import * as motion from '@carbon/motion';

// Carbon theme token -> CSS variable. Light theme is `white`, dark theme is `g100`.
const MAP = {
  background: 'bg',
  backgroundHover: 'bg-hover',
  layer01: 'layer',
  layer02: 'layer-2',
  layerHover01: 'layer-hover',
  layerAccent01: 'layer-accent',
  borderSubtle00: 'border',
  borderSubtle01: 'border-2',
  borderStrong01: 'border-strong',
  textPrimary: 'text',
  textSecondary: 'text-2',
  textPlaceholder: 'text-3',
  textInverse: 'text-inverse',
  textOnColor: 'text-on-color',
  linkPrimary: 'link',
  linkPrimaryHover: 'link-hover',
  focus: 'focus',
  iconPrimary: 'icon',
  highlight: 'highlight',
  supportSuccess: 'success',
  supportWarning: 'warning',
  supportError: 'error',
};

function block(selector, theme, label) {
  const lines = Object.entries(MAP).map(([token, name]) => {
    const value = theme[token];
    if (typeof value !== 'string') {
      throw new Error(`@carbon/themes ${label} has no string token "${token}". Update scripts/lib/build-tokens.mjs for this version.`);
    }
    return `  --${name}: ${value};`;
  });
  return `${selector} {\n${lines.join('\n')}\n}`;
}

function need(source, key, label) {
  const v = source[key];
  if (v === undefined) throw new Error(`${label} has no export "${key}". Update scripts/lib/build-tokens.mjs for this version.`);
  return v;
}

export async function buildTokensCss() {
  const { white, g100 } = themes;
  if (!white || !g100) throw new Error('@carbon/themes did not export `white` and `g100`. Check the package version.');

  const c = (k) => need(colors, k, '@carbon/colors');
  const palette = {
    'blue-40': c('blue40'),
    'blue-50': c('blue50'),
    'blue-60': c('blue60'),
    'blue-60-hover': c('blue60Hover'),
    'blue-70': c('blue70'),
    'gray-100': c('gray100'),
    'gray-90': c('gray90'),
    'gray-80': c('gray80'),
    'gray-80-hover': c('gray80Hover'),
    'gray-70': c('gray70'),
    'gray-20': c('gray20'),
    'gray-10': c('gray10'),
    white: c('white'),
  };
  const paletteCss = Object.entries(palette)
    .map(([n, v]) => `  --c-${n}: ${v};`)
    .join('\n');

  // The only place red, yellow and green appear: the change vocabulary (added, changed, removed).
  const diff = [`  --diff-added: ${c('green50')};`, `  --diff-changed: ${c('yellow30')};`, `  --diff-removed: ${c('red60')};`].join('\n');

  const e = need(motion, 'easings', '@carbon/motion');
  const dur = (k) => need(motion, k, '@carbon/motion');
  const motionCss = [
    `  --ease-productive: ${e.standard.productive};`,
    `  --ease-expressive: ${e.standard.expressive};`,
    `  --ease-entrance: ${e.entrance.expressive};`,
    `  --dur-fast: ${dur('durationFast02')};`,
    `  --dur-moderate: ${dur('durationModerate02')};`,
    `  --dur-slow: ${dur('durationSlow01')};`,
    `  --dur-slower: ${dur('durationSlow02')};`,
  ].join('\n');

  return [
    '/* Generated by scripts/lib/build-tokens.mjs from @carbon/themes, @carbon/colors and @carbon/motion. Do not edit. */',
    block(':root,\n[data-theme="light"]', white, '`white`'),
    block('[data-theme="dark"],\n.g100', g100, '`g100`'),
    `:root {\n${paletteCss}\n${diff}\n${motionCss}\n}`,
    '',
  ].join('\n\n');
}
